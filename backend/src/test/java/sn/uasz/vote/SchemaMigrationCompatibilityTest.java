package sn.uasz.vote;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.boot.jdbc.DataSourceBuilder;
import org.springframework.orm.jpa.LocalContainerEntityManagerFactoryBean;
import org.springframework.orm.jpa.vendor.HibernateJpaVendorAdapter;

import javax.sql.DataSource;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.Properties;

import static org.junit.jupiter.api.Assertions.*;

@DisplayName("Compatibilité schéma ddl-auto=update et script SQL force-password-change.sql")
class SchemaMigrationCompatibilityTest {

    @Test
    @DisplayName("ddl-auto=update sur base déjà peuplée et exécution du script docs/sql/force-password-change.sql")
    void ddlAutoUpdateAndForcePasswordChangeSql_workOnPopulatedDatabase() throws Exception {
        String dbUrl = "jdbc:h2:mem:pg_compat_" + System.nanoTime() + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1";
        DataSource ds = DataSourceBuilder.create()
                .url(dbUrl)
                .username("sa")
                .password("")
                .build();

        // 1. Créer les tables AVANT l'ajout de must_change_password et attempts_count et y insérer des données
        try (Connection conn = ds.getConnection(); Statement st = conn.createStatement()) {
            st.execute("""
                    CREATE TABLE users (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        matricule VARCHAR(255) NOT NULL UNIQUE,
                        nom VARCHAR(255) NOT NULL,
                        prenom VARCHAR(255) NOT NULL,
                        email VARCHAR(255) NOT NULL UNIQUE,
                        telephone VARCHAR(255),
                        password VARCHAR(255) NOT NULL,
                        role VARCHAR(50) NOT NULL,
                        type_electeur VARCHAR(50),
                        ufr VARCHAR(255),
                        filiere VARCHAR(255),
                        niveau VARCHAR(255),
                        is_active BOOLEAN NOT NULL,
                        failed_login_attempts INTEGER DEFAULT 0 NOT NULL,
                        locked_until TIMESTAMP,
                        created_at TIMESTAMP NOT NULL
                    )
                    """);
            st.execute("""
                    CREATE TABLE password_reset_tokens (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        code_hash VARCHAR(255) NOT NULL,
                        user_id BIGINT NOT NULL,
                        expires_at TIMESTAMP NOT NULL,
                        is_used BOOLEAN NOT NULL,
                        created_at TIMESTAMP NOT NULL
                    )
                    """);
            st.execute("INSERT INTO users (matricule, nom, prenom, email, password, role, is_active, created_at) "
                    + "VALUES ('ADMIN01', 'Admin', 'Root', 'admin@uasz.sn', 'hash', 'SUPER_ADMIN', true, CURRENT_TIMESTAMP)");
            st.execute("INSERT INTO users (matricule, nom, prenom, email, password, role, is_active, created_at) "
                    + "VALUES ('ELEC01', 'Diop', 'Awa', 'elec01@uasz.sn', 'hash', 'ELECTEUR', true, CURRENT_TIMESTAMP)");
            st.execute("INSERT INTO users (matricule, nom, prenom, email, password, role, is_active, created_at) "
                    + "VALUES ('CAND01', 'Fall', 'Moussa', 'cand01@uasz.sn', 'hash', 'CANDIDAT', true, CURRENT_TIMESTAMP)");
            st.execute("INSERT INTO password_reset_tokens (code_hash, user_id, expires_at, is_used, created_at) "
                    + "VALUES ('codehash', 2, CURRENT_TIMESTAMP, false, CURRENT_TIMESTAMP)");
        }

        // 2. Exécuter Hibernate ddl-auto=update sur la base déjà peuplée
        LocalContainerEntityManagerFactoryBean emf = new LocalContainerEntityManagerFactoryBean();
        emf.setDataSource(ds);
        emf.setPackagesToScan("sn.uasz.vote.entity");
        HibernateJpaVendorAdapter adapter = new HibernateJpaVendorAdapter();
        emf.setJpaVendorAdapter(adapter);
        Properties props = new Properties();
        props.setProperty("hibernate.hbm2ddl.auto", "update");
        emf.setJpaProperties(props);
        emf.afterPropertiesSet();
        emf.destroy();

        // 3. Vérifier les valeurs par défaut sur les lignes préexistantes
        try (Connection conn = ds.getConnection(); Statement st = conn.createStatement()) {
            ResultSet rsPrt = st.executeQuery("SELECT attempts_count FROM password_reset_tokens WHERE id = 1");
            assertTrue(rsPrt.next());
            assertEquals(0, rsPrt.getInt("attempts_count"));

            ResultSet rsUser = st.executeQuery("SELECT must_change_password FROM users WHERE matricule = 'ELEC01'");
            assertTrue(rsUser.next());
            assertFalse(rsUser.getBoolean("must_change_password"));

            // 4. Exécuter le script SQL docs/sql/force-password-change.sql
            Path sqlPath = Path.of("../docs/sql/force-password-change.sql");
            if (!Files.exists(sqlPath)) {
                sqlPath = Path.of("docs/sql/force-password-change.sql");
            }
            String sql = Files.readString(sqlPath);
            for (String stmt : sql.split(";")) {
                String cleaned = stmt.replaceAll("(?m)^--.*$", "").trim();
                if (!cleaned.isEmpty() && !cleaned.toUpperCase().startsWith("SELECT")) {
                    st.execute(cleaned);
                }
            }

            ResultSet rsVerify = st.executeQuery(
                    "SELECT role, must_change_password, COUNT(*) AS total FROM users GROUP BY role, must_change_password ORDER BY role");
            while (rsVerify.next()) {
                String role = rsVerify.getString("role");
                boolean mustChange = rsVerify.getBoolean("must_change_password");
                long total = rsVerify.getLong("total");
                assertEquals(1L, total);
                if ("SUPER_ADMIN".equals(role)) {
                    assertFalse(mustChange);
                } else {
                    assertTrue(mustChange);
                }
            }
        }
    }
}
